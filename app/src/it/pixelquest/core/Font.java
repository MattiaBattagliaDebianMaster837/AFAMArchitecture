    public static final int GW = 5, GH = 7, ADV = 6;
    private static final long[] GLYPHS = new long[256];
    private static final boolean[] HAS = new boolean[256];

    private static void g(char c, String... rows) {
        long bits = 0;
        for (int y = 0; y < 7; y++)
            for (int x = 0; x < 5; x++)
                if (rows[y].charAt(x) == '#') bits |= 1L << (y * 5 + x);
        GLYPHS[c] = bits;
        HAS[c] = true;
    }

