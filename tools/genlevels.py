#!/usr/bin/env python3
"""
Converts levels/levels.txt into app/src/it/pixelquest/core/Levels.java.

Format:
  @level <index> <boss|normal> <NAME...>
  @hint <text>            (one per 'i' sign, in left-to-right order)
  rows of a chunk ('.' = empty)
  +                        (chunk separator; chunks are concatenated horizontally)
  @end
"""
import sys
import re

SRC = sys.argv[1] if len(sys.argv) > 1 else "levels/levels.txt"
OUT = sys.argv[2] if len(sys.argv) > 2 else "app/src/it/pixelquest/core/Levels.java"

VALID = set(" .#=Bb?MhLI*-^~%okPCGgsrvfpxXTmwnFKieuYZzql<>AVUtajcdyO")


def parse(path):
    levels = []
    cur = None
    chunk = []
    for ln, raw in enumerate(open(path, encoding="utf-8"), 1):
        line = raw.rstrip("\n")
        if line.startswith("#!"):
            continue
        if line.startswith("@level"):
            parts = line.split(None, 3)
            cur = {"index": int(parts[1]), "boss": parts[2] == "boss", "name": parts[3].strip(),
                   "hints": [], "chunks": [], "line": ln}
            chunk = []
            continue
        if cur is None:
            continue
        if line.startswith("@hint"):
            cur["hints"].append(line[5:].strip())
            continue
        if line.startswith("@autoscroll"):
            cur["autoscroll"] = float(line.split()[1])
            continue
        if line.strip() == "+" or line.startswith("@end"):
            if chunk:
                cur["chunks"].append(chunk)
            chunk = []
            if line.startswith("@end"):
                levels.append(cur)
                cur = None
            continue
        if line.strip() == "":
            continue
        chunk.append(line)
    return levels


def build(lv):
    hs = {len(c) for c in lv["chunks"]}
    if len(hs) != 1:
        raise SystemExit("level %d: chunk heights differ %s" % (lv["index"], [len(c) for c in lv["chunks"]]))
    h = hs.pop()
    rows = [""] * h
    for c in lv["chunks"]:
        w = max(len(r) for r in c)
        for i, r in enumerate(c):
            rows[i] += r.ljust(w, ".")
    rows = [r.replace(".", " ") for r in rows]
    return rows


def check(lv, rows):
    errs = []
    text = "".join(rows)
    bad = set(text) - VALID
    if bad:
        errs.append("invalid chars %s" % bad)
    if text.count("P") != 1:
        errs.append("needs exactly one P (has %d)" % text.count("P"))
    if lv["boss"]:
        if text.count("K") != 1:
            errs.append("boss level needs one K")
        k = [r.find("K") for r in rows if "K" in r][0]
        if len(rows[0]) - k != 34:
            errs.append("arena must be 34 wide (is %d)" % (len(rows[0]) - k))
    else:
        if text.count("G") != 1:
            errs.append("needs exactly one G (has %d)" % text.count("G"))
        if text.count("g") != 3:
            errs.append("needs 3 gems (has %d)" % text.count("g"))
    if text.count("i") != len(lv["hints"]):
        errs.append("signs %d != hints %d" % (text.count("i"), len(lv["hints"])))
    # walkers must have something under them (within 4 tiles)
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch in "srfpTCGiPzqltjc":
                ok = False
                for rr in range(r + 1, min(len(rows), r + 5)):
                    if rows[rr][c] in "#=BbMhL?*I-^kYZ<>AVU":
                        ok = True
                        break
                if not ok:
                    errs.append("'%s' at col %d row %d floats over nothing" % (ch, c, r))
    return errs


def jstr(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) > 126:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    levels = sorted(parse(SRC), key=lambda l: l["index"])
    out = []
    out.append("package it.pixelquest.core;\n")
    out.append("/** GENERATED by tools/genlevels.py from levels/levels.txt - do not edit by hand. */")
    out.append("public final class Levels {")
    out.append("    private static final LevelDef[] ALL = new LevelDef[%d];\n" % len(levels))
    out.append("    public static LevelDef get(int i) {")
    out.append("        if (ALL[i] == null) ALL[i] = make(i);")
    out.append("        return ALL[i];")
    out.append("    }\n")
    out.append("    public static int count() {")
    out.append("        return ALL.length;")
    out.append("    }\n")
    out.append("    private static LevelDef make(int i) {")
    out.append("        switch (i) {")
    failed = False
    for lv in levels:
        rows = build(lv)
        errs = check(lv, rows)
        print("level %2d %-24s %3dx%-2d  %s" % (lv["index"], lv["name"], len(rows[0]), len(rows),
                                              "OK" if not errs else "ERRORS"))
        for e in errs:
            print("    -", e)
            failed = True
        out.append("            case %d: return L%d();" % (lv["index"], lv["index"]))
    out.append("        }")
    out.append("        throw new IllegalArgumentException();")
    out.append("    }\n")
    for lv in levels:
        rows = build(lv)
        out.append("    private static LevelDef L%d() {" % lv["index"])
        out.append("        LevelDef d = new LevelDef(%d, %s, %s, new String[]{" % (
            lv["index"], jstr(lv["name"]), "true" if lv["boss"] else "false"))
        for r in rows:
            out.append("                " + jstr(r) + ",")
        out.append("        });")
        if lv["hints"]:
            out.append("        d.hints = new String[]{" + ", ".join(jstr(h) for h in lv["hints"]) + "};")
        if lv.get("autoscroll"):
            out.append("        d.autoscroll = %sf;" % lv["autoscroll"])
        out.append("        return d;")
        out.append("    }\n")
    out.append("}")
    if failed:
        raise SystemExit("level validation failed")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
